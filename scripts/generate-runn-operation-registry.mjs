#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const docsUrl = "https://developer.runn.io/openapi/v1.0.0.json";
const outputUrl = new URL(
  "../backend/src/modules/marketplace/connectors/runn/runn-operation-registry.ts",
  import.meta.url,
);
const response = await fetch(docsUrl, {
  headers: { Accept: "application/json" },
  redirect: "error",
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok)
  throw new Error(`${docsUrl} returned HTTP ${response.status}`);
const document = await response.json();
if (document?.openapi !== "3.1.0")
  throw new Error("Unexpected Runn OpenAPI version");

const operations = [];
for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const operation = pathItem[method];
    if (!operation) continue;
    const parameters = [
      ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
      ...(Array.isArray(operation.parameters) ? operation.parameters : []),
    ];
    operations.push({
      id: operation.operationId,
      method: method.toUpperCase(),
      path,
      summary:
        operation.summary ?? operation.description ?? `${method} ${path}`,
      pathParameters: parameters
        .filter((item) => item.in === "path")
        .map((item) => item.name),
      queryParameters: parameters
        .filter((item) => item.in === "query")
        .map((item) => item.name),
      bodyAllowed: Boolean(operation.requestBody),
    });
  }
}
const unique = [
  ...new Map(operations.map((item) => [item.id, item])).values(),
].sort((a, b) => a.id.localeCompare(b.id));
const reads = unique.filter((item) => item.method === "GET").length;
if (unique.length !== 196 || reads !== 92)
  throw new Error(
    `Expected 196 operations and 92 reads; received ${unique.length} and ${reads}`,
  );
const sourceHash = createHash("sha256")
  .update(JSON.stringify(document))
  .digest("hex");
const generated =
  `// Generated by scripts/generate-runn-operation-registry.mjs.\n` +
  `// Source: ${docsUrl}.\n` +
  `// SHA-256: ${sourceHash}\n\n` +
  `export type RunnOperation = {\n  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n  path: string;\n  summary: string;\n  pathParameters: readonly string[];\n  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n};\n\n` +
  `export const RUNN_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n\n` +
  `export const RUNN_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly RunnOperation[];\n\n` +
  `export const RUNN_READ_OPERATION_IDS = RUNN_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
  `export const RUNN_MANAGE_OPERATION_IDS = RUNN_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n` +
  `export const RUNN_OPERATION_BY_ID = new Map<string, RunnOperation>(RUNN_OPERATIONS.map((operation) => [operation.id, operation]));\n`;
await writeFile(fileURLToPath(outputUrl), generated, "utf8");
console.log(
  JSON.stringify({
    sourceHash,
    operations: unique.length,
    reads,
    writes: unique.length - reads,
  }),
);
