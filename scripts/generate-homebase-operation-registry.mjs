#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sourceUrl = "https://app.joinhomebase.com/api/public/swagger_doc.json";
const outputUrl = new URL(
  "../backend/src/modules/marketplace/connectors/homebase/homebase-operation-registry.ts",
  import.meta.url,
);

const response = await fetch(sourceUrl, {
  headers: { Accept: "application/json" },
  redirect: "error",
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok) {
  throw new Error(`Homebase Swagger returned HTTP ${response.status}`);
}
const sourceText = await response.text();
const document = JSON.parse(sourceText);
if (document.swagger !== "2.0" || !document.paths) {
  throw new Error("Homebase did not return the expected Swagger 2.0 contract");
}

const operations = [];
for (const [path, pathItem] of Object.entries(document.paths)) {
  const operation = pathItem.get;
  if (!operation) continue;
  const parameters = [
    ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
    ...(Array.isArray(operation.parameters) ? operation.parameters : []),
  ];
  operations.push({
    id: operation.operationId,
    method: "GET",
    path,
    summary:
      operation.summary || operation.description || operation.operationId,
    pathParameters: parameters
      .filter((parameter) => parameter.in === "path")
      .map((parameter) => parameter.name),
    queryParameters: parameters
      .filter((parameter) => parameter.in === "query")
      .map((parameter) => parameter.name),
  });
}
operations.sort((left, right) => left.id.localeCompare(right.id));
if (operations.length !== 16 || operations.some((operation) => !operation.id)) {
  throw new Error(
    `Expected 16 named Homebase GET operations, received ${operations.length}`,
  );
}

const sourceHash = createHash("sha256").update(sourceText).digest("hex");
const generated =
  `// Generated by scripts/generate-homebase-operation-registry.mjs.\n` +
  `// Source: ${sourceUrl}\n` +
  `// SHA-256: ${sourceHash}\n\n` +
  `export type HomebaseOperation = {\n` +
  `  id: string;\n` +
  `  method: \"GET\";\n` +
  `  path: string;\n` +
  `  summary: string;\n` +
  `  pathParameters: readonly string[];\n` +
  `  queryParameters: readonly string[];\n` +
  `};\n\n` +
  `export const HOMEBASE_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n\n` +
  `export const HOMEBASE_OPERATIONS = ${JSON.stringify(operations, null, 2)} as const satisfies readonly HomebaseOperation[];\n\n` +
  `export const HOMEBASE_OPERATION_IDS = HOMEBASE_OPERATIONS.map((operation) => operation.id);\n\n` +
  `export const HOMEBASE_OPERATION_BY_ID = new Map<string, HomebaseOperation>(HOMEBASE_OPERATIONS.map((operation) => [operation.id, operation]));\n`;

await writeFile(fileURLToPath(outputUrl), generated, "utf8");
console.log(
  JSON.stringify({
    source: sourceUrl,
    sourceHash,
    operations: operations.length,
    output: fileURLToPath(outputUrl),
  }),
);
