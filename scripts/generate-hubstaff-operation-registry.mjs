import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const docsUrl = "https://api.hubstaff.com/v2/docs";
const response = await fetch(docsUrl, { redirect: "error" });
if (!response.ok) throw new Error(`${docsUrl} returned ${response.status}`);
const spec = await response.json();
if (spec?.swagger !== "2.0" || spec?.info?.title !== "Hubstaff V2 API") {
  throw new Error("Unexpected Hubstaff API specification.");
}

const sortDeep = (value) =>
  Array.isArray(value)
    ? value.map(sortDeep)
    : value && typeof value === "object"
      ? Object.fromEntries(
          Object.entries(value)
            .sort(([left], [right]) => left.localeCompare(right))
            .map(([key, item]) => [key, sortDeep(item)]),
        )
      : value;
const sourceSha256 = createHash("sha256")
  .update(JSON.stringify(sortDeep(spec)))
  .digest("hex");

// Webhook creation, verification, activation, and secret handling are provider
// callback/authentication plumbing. They require a dedicated signed ingress
// service and are not user workspace resources exposed to agents.
const excludedTags = new Set(["webhooks"]);
const methods = new Set(["get", "post", "put", "patch", "delete"]);
const operations = [];
for (const [path, pathItem] of Object.entries(spec.paths)) {
  for (const [rawMethod, operation] of Object.entries(pathItem)) {
    const method = rawMethod.toLowerCase();
    if (
      !methods.has(method) ||
      (operation.tags ?? []).some((tag) => excludedTags.has(tag))
    )
      continue;
    const parameters = [
      ...(pathItem.parameters ?? []),
      ...(operation.parameters ?? []),
    ];
    operations.push({
      id: operation.operationId,
      method: method.toUpperCase(),
      path,
      group: operation.tags?.[0] ?? "Hubstaff",
      pathParameters: [
        ...new Set(
          parameters
            .filter((item) => item.in === "path")
            .map((item) => item.name),
        ),
      ],
      queryParameters: [
        ...new Set(
          parameters
            .filter((item) => item.in === "query")
            .map((item) => item.name),
        ),
      ],
      bodyAllowed: parameters.some((item) => item.in === "body"),
    });
  }
}
const unique = [
  ...new Map(operations.map((operation) => [operation.id, operation])).values(),
].sort((left, right) => left.id.localeCompare(right.id));
const reads = unique.filter((operation) => operation.method === "GET").length;
const mutations = unique.length - reads;
if (unique.length !== 160 || reads !== 96 || mutations !== 64) {
  throw new Error(
    `Unexpected Hubstaff surface: ${unique.length}/${reads}/${mutations}`,
  );
}

const output = resolve(
  "backend/src/modules/marketplace/connectors/hubstaff/hubstaff-operation-registry.ts",
);
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/generate-hubstaff-operation-registry.mjs.\n` +
    `// Source: ${docsUrl}\n` +
    `// Canonical Swagger SHA-256: ${sourceSha256}\n` +
    `// Six webhook callback/secret lifecycle operations are deliberately excluded.\n\n` +
    `export type HubstaffOperation = {\n` +
    `  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n` +
    `  path: string;\n  group: string;\n  pathParameters: readonly string[];\n` +
    `  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n};\n\n` +
    `export const HUBSTAFF_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};\n\n` +
    `export const HUBSTAFF_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly HubstaffOperation[];\n\n` +
    `export const HUBSTAFF_OPERATION_BY_ID: ReadonlyMap<string, HubstaffOperation> = new Map(HUBSTAFF_OPERATIONS.map((operation) => [operation.id, operation]));\n` +
    `export const HUBSTAFF_READ_OPERATION_IDS = HUBSTAFF_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
    `export const HUBSTAFF_MANAGE_OPERATION_IDS = HUBSTAFF_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n`,
);
console.log(
  JSON.stringify(
    { output, sourceSha256, operations: unique.length, reads, mutations },
    null,
    2,
  ),
);
