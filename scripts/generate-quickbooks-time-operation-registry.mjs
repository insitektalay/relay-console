import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  mkdtemp,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const sourceCommit = "3cc0b81b2c380b85571bc44f7f55e7a553c451c4";
const docsUrl = "https://tsheetsteam.github.io/api_docs/";
const archiveUrl = `https://github.com/TSheetsTeam/api_docs/archive/${sourceCommit}.tar.gz`;
const response = await fetch(archiveUrl, { redirect: "follow" });
if (!response.ok) throw new Error(`${archiveUrl} returned ${response.status}`);
const archive = Buffer.from(await response.arrayBuffer());
const sourceSha256 = createHash("sha256").update(archive).digest("hex");
const temporaryRoot = await mkdtemp(join(tmpdir(), "quickbooks-time-api-"));
const archivePath = join(temporaryRoot, "source.tar.gz");
const extractedPath = join(temporaryRoot, "source");

const operationFiles = new Set([
  "_retrieve.md.erb",
  "_create.md.erb",
  "_update.md.erb",
  "_delete.md.erb",
  "_download.md.erb",
]);

const pascal = (value) =>
  value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const queryParameters = (markdown) => {
  const heading = /^### (?:Filter Parameters|Parameters)\s*$/m.exec(markdown);
  if (!heading) return [];
  const tail = markdown.slice(heading.index + heading[0].length);
  const nextHeading = /\n#{2,3} /m.exec(tail);
  const section = nextHeading ? tail.slice(0, nextHeading.index) : tail;
  return [
    ...new Set(
      [...section.matchAll(/^\| \*\*([A-Za-z][A-Za-z0-9_]*)\*\*/gm)].map(
        (match) => match[1],
      ),
    ),
  ];
};

try {
  await writeFile(archivePath, archive);
  await mkdir(extractedPath);
  execFileSync("tar", [
    "-xzf",
    archivePath,
    "-C",
    extractedPath,
    "--strip-components=1",
  ]);
  const referenceRoot = join(
    extractedPath,
    "source/includes/APIReference",
  );
  const operations = [];
  for (const group of await readdir(referenceRoot, { withFileTypes: true })) {
    if (!group.isDirectory()) continue;
    const groupPath = join(referenceRoot, group.name);
    for (const entry of await readdir(groupPath, { withFileTypes: true })) {
      if (!entry.isFile()) continue;
      const isReport =
        group.name === "Reports" && entry.name !== "_reports.md.erb";
      if (!operationFiles.has(entry.name) && !isReport) continue;
      const markdown = await readFile(join(groupPath, entry.name), "utf8");
      const requestPattern =
        /<img src="images\/(get|post|put|delete)\.png" alt="[^"]+"\/><api>https:\/\/rest\.tsheets\.com\/api\/v1([^<]+)<\/api>/g;
      for (const match of markdown.matchAll(requestPattern)) {
        const method = match[1].toUpperCase();
        const path = match[2];
        operations.push({
          id: `${method.toLowerCase()}${pascal(path)}`,
          method,
          path,
          group: group.name,
          pathParameters: [],
          queryParameters:
            method === "GET" || method === "DELETE"
              ? queryParameters(markdown)
              : [],
          bodyAllowed: method === "POST" || method === "PUT",
          responseType: path === "/files/raw" ? "binary" : "json",
        });
      }
    }
  }
  const unique = [
    ...new Map(operations.map((operation) => [operation.id, operation])).values(),
  ].sort((left, right) => left.id.localeCompare(right.id));
  const reads = unique.filter((operation) => operation.method === "GET").length;
  const mutations = unique.length - reads;
  if (unique.length !== 86 || reads !== 34 || mutations !== 52) {
    throw new Error(
      `Unexpected QuickBooks Time surface: ${unique.length}/${reads}/${mutations}`,
    );
  }
  const output = resolve(
    "backend/src/modules/marketplace/connectors/quickbooks-time/quickbooks-time-operation-registry.ts",
  );
  await mkdir(dirname(output), { recursive: true });
  await writeFile(
    output,
    `// Generated by scripts/generate-quickbooks-time-operation-registry.mjs.\n` +
      `// Source: ${docsUrl}\n` +
      `// Source commit: ${sourceCommit}\n` +
      `// Canonical archive SHA-256: ${sourceSha256}\n\n` +
      `export type QuickBooksTimeOperation = {\n` +
      `  id: string;\n  method: "GET" | "POST" | "PUT" | "DELETE";\n` +
      `  path: string;\n  group: string;\n  pathParameters: readonly string[];\n` +
      `  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n` +
      `  responseType: "json" | "binary";\n};\n\n` +
      `export const QUICKBOOKS_TIME_SOURCE_COMMIT = ${JSON.stringify(sourceCommit)};\n` +
      `export const QUICKBOOKS_TIME_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};\n\n` +
      `export const QUICKBOOKS_TIME_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly QuickBooksTimeOperation[];\n\n` +
      `export const QUICKBOOKS_TIME_OPERATION_BY_ID: ReadonlyMap<string, QuickBooksTimeOperation> = new Map(QUICKBOOKS_TIME_OPERATIONS.map((operation) => [operation.id, operation]));\n` +
      `export const QUICKBOOKS_TIME_READ_OPERATION_IDS = QUICKBOOKS_TIME_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
      `export const QUICKBOOKS_TIME_MANAGE_OPERATION_IDS = QUICKBOOKS_TIME_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n`,
  );
  console.log(
    JSON.stringify(
      { output, sourceCommit, sourceSha256, operations: unique.length, reads, mutations },
      null,
      2,
    ),
  );
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}
