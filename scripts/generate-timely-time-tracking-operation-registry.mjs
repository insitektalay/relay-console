#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const docsUrl = "https://developer.timely.com/";
const outputUrl = new URL(
  "../backend/src/modules/marketplace/connectors/timely-time-tracking/timely-time-tracking-operation-registry.ts",
  import.meta.url,
);

const response = await fetch(docsUrl, {
  headers: { Accept: "text/html" },
  redirect: "error",
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok)
  throw new Error(`${docsUrl} returned HTTP ${response.status}`);
const html = await response.text();
const match = html.match(
  /<script\s+id="api-reference"[\s\S]*?>([\s\S]*?)<\/script>/,
);
if (!match) throw new Error("Timely embedded OpenAPI document was not found");
const document = JSON.parse(match[1].trim());
if (document?.openapi !== "3.1.0")
  throw new Error("Unexpected Timely OpenAPI version");

const idFor = (method, path) =>
  `${method}_${path}`
    .toLowerCase()
    .replace(/\{([^}]+)\}/g, "by_$1")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
const operations = [];
for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
  if (path === "/webhook-events" || path.startsWith("/1.1/oauth/")) continue;
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const operation = pathItem[method];
    if (!operation) continue;
    const parameters = [
      ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
      ...(Array.isArray(operation.parameters) ? operation.parameters : []),
    ];
    operations.push({
      id: idFor(method, path),
      method: method.toUpperCase(),
      path,
      summary:
        operation.summary ?? operation.description ?? `${method} ${path}`,
      pathParameters: parameters
        .filter((item) => item.in === "path")
        .map((item) => item.name),
      queryParameters: parameters
        .filter((item) => item.in === "query")
        .map((item) => item.name),
      bodyAllowed: Boolean(operation.requestBody),
    });
  }
}
// The introduction explicitly documents GET /1.1/accounts as the account
// discovery call even though the current generated paths table omits it.
operations.push({
  id: "get_1_1_accounts",
  method: "GET",
  path: "/1.1/accounts",
  summary: "List accounts available to the authenticated user",
  pathParameters: [],
  queryParameters: [],
  bodyAllowed: false,
});
const unique = [
  ...new Map(operations.map((item) => [item.id, item])).values(),
].sort((a, b) => a.id.localeCompare(b.id));
const reads = unique.filter((item) => item.method === "GET").length;
if (unique.length !== 70 || reads !== 32)
  throw new Error(
    `Expected 70 application operations and 32 reads; received ${unique.length} and ${reads}`,
  );
const sourceHash = createHash("sha256")
  .update(JSON.stringify(document))
  .digest("hex");
const generated =
  `// Generated by scripts/generate-timely-time-tracking-operation-registry.mjs.\n` +
  `// Source: ${docsUrl}.\n` +
  `// SHA-256: ${sourceHash}\n\n` +
  `export type TimelyTimeTrackingOperation = {\n  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n  path: string;\n  summary: string;\n  pathParameters: readonly string[];\n  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n};\n\n` +
  `export const TIMELY_TIME_TRACKING_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n\n` +
  `export const TIMELY_TIME_TRACKING_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly TimelyTimeTrackingOperation[];\n\n` +
  `export const TIMELY_TIME_TRACKING_READ_OPERATION_IDS = TIMELY_TIME_TRACKING_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
  `export const TIMELY_TIME_TRACKING_MANAGE_OPERATION_IDS = TIMELY_TIME_TRACKING_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n` +
  `export const TIMELY_TIME_TRACKING_OPERATION_BY_ID = new Map<string, TimelyTimeTrackingOperation>(TIMELY_TIME_TRACKING_OPERATIONS.map((operation) => [operation.id, operation]));\n`;
await writeFile(fileURLToPath(outputUrl), generated, "utf8");
console.log(
  JSON.stringify({
    sourceHash,
    operations: unique.length,
    reads,
    writes: unique.length - reads,
  }),
);
