#!/usr/bin/env node

import { createHash } from "node:crypto"
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const PROVIDERS_ROOT = resolve(ROOT, "packages/marketplace-catalog/providers")
const LEDGER_PATH = resolve(
  ROOT,
  "RelayConsoleSwift/agent-loops/agent-loop-marketplace-shared-convergence/candidate-ledger.csv",
)
const CATALOG_SNAPSHOT_PATH = resolve(
  ROOT,
  "backend/src/modules/marketplace/catalog/generated-provider-catalog.json",
)
const TYPESCRIPT_IDENTITIES_PATH = resolve(
  ROOT,
  "backend/src/modules/marketplace/catalog/generated-provider-identities.ts",
)
const SWIFT_CATALOG_SNAPSHOT_PATH = resolve(
  ROOT,
  "RelayConsoleSwift/Sources/RelayConsoleCore/Resources/marketplace-provider-catalog.json",
)
const RELEASE_MANIFEST_PATH = resolve(
  ROOT,
  "packages/marketplace-catalog/release/marketplace-release-manifest.json",
)
const RELEASE_SNAPSHOT_PATHS = [
  resolve(ROOT, "backend/src/modules/marketplace/marketplace-release-manifest.json"),
  resolve(
    ROOT,
    "RelayConsoleSwift/Sources/RelayConsoleCore/Resources/marketplace-release-manifest.json",
  ),
]
const CLIENT_SUPPORTED_RUNTIME_STATES = new Set([
  "installable",
  "native",
  "native_tools",
  "native_wrapper_tools",
  "server_proxy",
  "preview_only",
])

function normalizedJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`
}

function parseLedger() {
  const lines = readFileSync(LEDGER_PATH, "utf8").trim().split(/\r?\n/)
  const headings = lines.shift().split(",")
  return lines.map((line) => {
    const values = line.split(",")
    return Object.fromEntries(headings.map((heading, index) => [heading, values[index] ?? ""]))
  })
}

function loadManifests() {
  return readdirSync(PROVIDERS_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) =>
      JSON.parse(
        readFileSync(resolve(PROVIDERS_ROOT, entry.name, "manifest.json"), "utf8"),
      ),
    )
    .sort((left, right) => left.slug.localeCompare(right.slug))
}

function customerCredentialCohort(manifests) {
  const manifestsByPath = new Map(
    manifests.map((manifest) => [
      `packages/marketplace-catalog/providers/${manifest.slug}/manifest.json`,
      manifest,
    ]),
  )
  const cohort = new Map()
  for (const row of parseLedger()) {
    if (row.Outcome !== "code-complete-awaiting-provider-setup") continue
    const manifest = manifestsByPath.get(row["Manifest Path"])
    const supportsCustomerOwnedCredentials =
      manifest?.authentication?.relayOwned === false ||
      manifest?.connection?.types?.includes("customer_owned_api_key")
    if (
      !manifest ||
      !supportsCustomerOwnedCredentials ||
      manifest.authentication?.model === "unsupported" ||
      !manifest.connection?.credentialRequirements?.length
    ) {
      continue
    }
    cohort.set(manifest.slug, manifest)
  }
  return [...cohort.values()].sort((left, right) => left.slug.localeCompare(right.slug))
}

function boundedLaunchCohort(manifests) {
  return customerCredentialCohort(manifests).filter(
    (manifest) =>
      ((manifest.actions?.allowed?.length ?? 0) > 0 ||
        (manifest.actions?.approvalRequired?.length ?? 0) > 0) &&
      (manifest.runtimeSupport ?? []).some(
        (runtime) => runtime.installSupport !== "unsupported",
      ),
  )
}

function frozenReleaseManifest(manifests) {
  const manifest = JSON.parse(readFileSync(RELEASE_MANIFEST_PATH, "utf8"))
  const expectedSlugs = boundedLaunchCohort(manifests).map(({ slug }) => slug)
  const actualSlugs = manifest.providers?.map(({ slug }) => slug) ?? []
  if (
    manifest.freeze?.status !== "frozen" ||
    expectedSlugs.length !== 406 ||
    actualSlugs.length !== 406 ||
    expectedSlugs.some((slug, index) => slug !== actualSlugs[index])
  ) {
    throw new Error(
      "The frozen Marketplace launch cohort must remain the exact 406 bounded customer-credential providers selected for launch.",
    )
  }
  return manifest
}

function snapshot(manifests) {
  const material = normalizedJson(manifests)
  return {
    schemaVersion: "relay.marketplace-catalog.v1",
    generatedAt: "2026-07-19T00:00:00.000Z",
    manifestCount: manifests.length,
    sourceSHA256: createHash("sha256").update(material).digest("hex"),
    manifests,
  }
}

function typescriptIdentities(manifests, sourceSHA256) {
  const lines = [
    "// Generated by scripts/sync-marketplace-catalog.mjs. Do not edit by hand.",
    `export const GENERATED_MARKETPLACE_PROVIDER_SOURCE_SHA256 = ${JSON.stringify(sourceSHA256)} as const;`,
    "",
    "export const GENERATED_MARKETPLACE_PROVIDER_IDENTITIES = {",
  ]
  for (const manifest of manifests) {
    const executableActionIds = [
      ...(manifest.actions?.allowed ?? []),
      ...(manifest.actions?.approvalRequired ?? []),
    ].map(({ id }) => id)
    const identity = {
      name: manifest.name,
      authModel: manifest.authentication?.model ?? "unsupported",
      relayOwned: manifest.authentication?.relayOwned === true,
      capabilityIds: (manifest.capabilities ?? []).map(({ id }) => id),
      executableActionIds,
      blockedActionIds: (manifest.actions?.blocked ?? []).map(({ id }) => id),
      credentialFieldNames: (manifest.connection?.credentialRequirements ?? [])
        .map((credential) =>
          typeof credential === "string"
            ? credential
            : credential?.name ?? credential?.key ?? credential?.id,
        )
        .filter(Boolean),
      runtimeFormats: (manifest.runtimeSupport ?? [])
        .filter(({ installSupport }) =>
          CLIENT_SUPPORTED_RUNTIME_STATES.has(installSupport),
        )
        .map(({ format }) => format),
      availability: manifest.availability,
    }
    lines.push(`  ${JSON.stringify(manifest.slug)}: ${JSON.stringify(identity)},`)
  }
  lines.push(
    "} as const;",
    "",
    "export type MarketplaceProviderSlug = keyof typeof GENERATED_MARKETPLACE_PROVIDER_IDENTITIES;",
    "export type MarketplaceProviderIdentity<Slug extends MarketplaceProviderSlug = MarketplaceProviderSlug> = (typeof GENERATED_MARKETPLACE_PROVIDER_IDENTITIES)[Slug];",
    "export type MarketplaceExecutableActionId<Slug extends MarketplaceProviderSlug> = MarketplaceProviderIdentity<Slug>[\"executableActionIds\"][number];",
    "",
  )
  return lines.join("\n")
}

function checkFile(path, expected) {
  try {
    return readFileSync(path, "utf8") === expected
  } catch {
    return false
  }
}

const manifests = loadManifests()
const catalogSnapshot = snapshot(manifests)
const catalog = normalizedJson(catalogSnapshot)
const release = normalizedJson(frozenReleaseManifest(manifests))
const outputs = [
  [CATALOG_SNAPSHOT_PATH, catalog],
  [SWIFT_CATALOG_SNAPSHOT_PATH, catalog],
  [
    TYPESCRIPT_IDENTITIES_PATH,
    typescriptIdentities(manifests, catalogSnapshot.sourceSHA256),
  ],
  ...RELEASE_SNAPSHOT_PATHS.map((path) => [path, release]),
]

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, expected]) => !checkFile(path, expected))
  if (stale.length) {
    for (const [path] of stale) console.error(`Marketplace generated artifact is stale: ${path}`)
    process.exitCode = 1
  } else {
    console.log(
      `Marketplace catalog parity verified: ${manifests.length} manifests, ${boundedLaunchCohort(manifests).length} bounded launch providers.`,
    )
  }
} else {
  for (const [path, content] of outputs) writeFileSync(path, content)
  console.log(
    `Synchronized ${manifests.length} Marketplace manifests and ${boundedLaunchCohort(manifests).length} bounded launch decisions.`,
  )
}
