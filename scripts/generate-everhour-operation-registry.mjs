#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const docsUrl = "https://jsapi.apiary.io/apis/everhour.apib";
const outputUrl = new URL(
  "../backend/src/modules/marketplace/connectors/everhour/everhour-operation-registry.ts",
  import.meta.url,
);
const response = await fetch(docsUrl, {
  headers: { Accept: "text/vnd.apiblueprint+markdown" },
  redirect: "error",
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok)
  throw new Error(`${docsUrl} returned HTTP ${response.status}`);
const source = await response.text();
if (
  !source.includes("HOST: https://api.everhour.com") ||
  !source.includes("# Everhour API")
) {
  throw new Error("Unexpected Everhour API Blueprint");
}

const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
const operations = [];
let resourcePath = "";
for (const line of source.split(/\r?\n/)) {
  const resource = line.match(/^# (?!#).*? \[([^\]]+)\]\s*$/);
  if (resource?.[1]?.startsWith("/")) resourcePath = resource[1];
  const action = line.match(
    /^## (.*?) \[(GET|POST|PUT|PATCH|DELETE)(?: ([^\]]+))?\]\s*$/,
  );
  if (!action) continue;
  const title = action[1];
  const method = action[2];
  const rawPath = action[3] || resourcePath;
  const templateQuery = rawPath.match(/\{\?([^}]+)\}/)?.[1]?.split(",") ?? [];
  const withoutTemplate = rawPath.replace(/\{\?[^}]+\}/, "");
  const parsed = new URL(withoutTemplate, "https://api.everhour.com");
  const pathParameters = [...parsed.pathname.matchAll(/\{([^}]+)\}/g)].map(
    (match) => match[1],
  );
  const fixedQuery = Object.fromEntries(parsed.searchParams.entries());
  operations.push({
    id: slug(title),
    title,
    method,
    path: parsed.pathname,
    pathParameters,
    queryParameters: [
      ...new Set([...templateQuery, ...Object.keys(fixedQuery)]),
    ],
    fixedQuery,
    bodyAllowed: method !== "GET" && method !== "DELETE",
  });
}
const uniqueIds = new Set(operations.map((operation) => operation.id));
const reads = operations.filter(
  (operation) => operation.method === "GET",
).length;
if (
  operations.length !== 103 ||
  reads !== 40 ||
  uniqueIds.size !== operations.length
) {
  throw new Error(
    `Expected 103 unique operations and 40 reads; received ${operations.length}, ${uniqueIds.size}, and ${reads}`,
  );
}
const sourceHash = createHash("sha256").update(source).digest("hex");
const generated =
  `// Generated by scripts/generate-everhour-operation-registry.mjs.\n` +
  `// Source: ${docsUrl}.\n` +
  `// SHA-256: ${sourceHash}\n\n` +
  `export type EverhourOperation = {\n  id: string;\n  title: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n  path: string;\n  pathParameters: readonly string[];\n  queryParameters: readonly string[];\n  fixedQuery: Readonly<Record<string, string>>;\n  bodyAllowed: boolean;\n};\n\n` +
  `export const EVERHOUR_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n\n` +
  `export const EVERHOUR_OPERATIONS = ${JSON.stringify(operations, null, 2)} as const satisfies readonly EverhourOperation[];\n\n` +
  `export const EVERHOUR_READ_OPERATION_IDS = EVERHOUR_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
  `export const EVERHOUR_MANAGE_OPERATION_IDS = EVERHOUR_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n` +
  `export const EVERHOUR_OPERATION_BY_ID = new Map<string, EverhourOperation>(EVERHOUR_OPERATIONS.map((operation) => [operation.id, operation]));\n`;
await writeFile(fileURLToPath(outputUrl), generated, "utf8");
console.log(
  JSON.stringify({
    sourceHash,
    operations: operations.length,
    reads,
    writes: operations.length - reads,
  }),
);
