import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const sources = [
  "projects",
  "tasks",
  "clients",
  "billing_costing",
  "activities",
  "users",
  "time",
  "security",
].map((group) => ({
  group,
  url: `https://sb1.replicon.com/admin/docs/${group}.yaml`,
}));

const readName =
  /^(?:Get|BulkGet|Retrieve|List|Search|Query|Find|Calculate|Check|Validate|Is|Can|Has|Lookup|Resolve|Preview)/;
const operations = [];
const sourceBuffers = [];

for (const source of sources) {
  const response = await fetch(source.url, { redirect: "error" });
  if (!response.ok)
    throw new Error(`${source.url} returned ${response.status}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  sourceBuffers.push(buffer);
  const yaml = buffer.toString("utf8");
  const lines = yaml.split(/\r?\n/);
  let currentPath = null;
  let currentMethod = null;
  let current = null;
  for (const line of lines) {
    const path = /^  (\/[^:]+):\s*$/.exec(line);
    if (path) {
      if (current) operations.push(current);
      currentPath = path[1];
      currentMethod = null;
      current = null;
      continue;
    }
    if (!currentPath) continue;
    const method = /^    (get|post|put|patch|delete):\s*$/.exec(line);
    if (method) {
      if (current) operations.push(current);
      currentMethod = method[1].toUpperCase();
      current = {
        id: currentPath.slice(1).replace(".svc/", "."),
        method: currentMethod,
        path: currentPath,
        group: source.group,
        summary: "",
        bodyAllowed: false,
        readOnly: false,
      };
      continue;
    }
    if (!current) continue;
    const summary = /^      summary:\s*(.*)\s*$/.exec(line);
    if (summary) current.summary = summary[1].replace(/^['"]|['"]$/g, "");
    if (/^      requestBody:\s*$/.test(line)) current.bodyAllowed = true;
  }
  if (current) operations.push(current);
}

for (const operation of operations) {
  const operationName = operation.path.split("/").at(-1);
  operation.readOnly = readName.test(operationName);
}

const unique = [
  ...new Map(operations.map((operation) => [operation.id, operation])).values(),
].sort((left, right) => left.id.localeCompare(right.id));
const reads = unique.filter((operation) => operation.readOnly).length;
const mutations = unique.length - reads;
if (unique.length !== 158 || reads !== 102 || mutations !== 56) {
  throw new Error(
    `Unexpected Replicon surface: ${unique.length}/${reads}/${mutations}`,
  );
}

const sourceSha256 = createHash("sha256")
  .update(Buffer.concat(sourceBuffers))
  .digest("hex");
const output = resolve(
  "backend/src/modules/marketplace/connectors/replicon/replicon-operation-registry.ts",
);
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/generate-replicon-operation-registry.mjs.\n` +
    `// Sources: ${sources.map((source) => source.url).join(", ")}\n` +
    `// Combined source SHA-256: ${sourceSha256}\n\n` +
    `export type RepliconOperation = {\n` +
    `  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n` +
    `  path: string;\n  group: string;\n  summary: string;\n` +
    `  bodyAllowed: boolean;\n  readOnly: boolean;\n};\n\n` +
    `export const REPLICON_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};\n` +
    `export const REPLICON_SOURCE_URLS = ${JSON.stringify(
      sources.map((source) => source.url),
      null,
      2,
    )} as const;\n\n` +
    `export const REPLICON_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly RepliconOperation[];\n\n` +
    `export const REPLICON_OPERATION_BY_ID: ReadonlyMap<string, RepliconOperation> = new Map(REPLICON_OPERATIONS.map((operation) => [operation.id, operation]));\n` +
    `export const REPLICON_READ_OPERATION_IDS = REPLICON_OPERATIONS.filter((operation) => operation.readOnly).map((operation) => operation.id);\n` +
    `export const REPLICON_MANAGE_OPERATION_IDS = REPLICON_OPERATIONS.filter((operation) => !operation.readOnly).map((operation) => operation.id);\n`,
);
console.log(
  JSON.stringify(
    { output, sourceSha256, operations: unique.length, reads, mutations },
    null,
    2,
  ),
);
