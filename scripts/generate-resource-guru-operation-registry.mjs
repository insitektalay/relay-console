#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const docsUrl = "https://resourceguruapp.com/docs/api";
const outputUrl = new URL(
  "../backend/src/modules/marketplace/connectors/resource-guru/resource-guru-operation-registry.ts",
  import.meta.url,
);

const response = await fetch(docsUrl, {
  headers: { Accept: "text/html" },
  redirect: "error",
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok)
  throw new Error(`${docsUrl} returned HTTP ${response.status}`);
const html = await response.text();
const marker = "const __redoc_state = ";
const start = html.indexOf(marker);
const end = html.indexOf(";\n", start + marker.length);
if (start < 0 || end < 0)
  throw new Error("Resource Guru Redoc state was not found");
const state = JSON.parse(html.slice(start + marker.length, end));
const document = state?.spec?.data;
if (document?.openapi !== "3.0.3")
  throw new Error("Unexpected Resource Guru OpenAPI version");

const idFor = (method, path) =>
  `${method}_${path}`
    .toLowerCase()
    .replace(/\{([^}]+)\}/g, "by_$1")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
const operations = [];
for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const operation = pathItem[method];
    if (!operation) continue;
    const parameters = [
      ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
      ...(Array.isArray(operation.parameters) ? operation.parameters : []),
    ];
    operations.push({
      id: idFor(method, path),
      method: method.toUpperCase(),
      path,
      summary:
        operation.summary ?? operation.description ?? `${method} ${path}`,
      pathParameters: parameters
        .filter((item) => item.in === "path")
        .map((item) => item.name),
      queryParameters: parameters
        .filter((item) => item.in === "query")
        .map((item) => item.name),
      bodyAllowed: Boolean(operation.requestBody),
    });
  }
}
const unique = [
  ...new Map(operations.map((item) => [item.id, item])).values(),
].sort((a, b) => a.id.localeCompare(b.id));
const reads = unique.filter((item) => item.method === "GET").length;
if (unique.length !== 112 || reads !== 60)
  throw new Error(
    `Expected 112 operations and 60 reads; received ${unique.length} and ${reads}`,
  );
const sourceHash = createHash("sha256")
  .update(JSON.stringify(document))
  .digest("hex");
const generated =
  `// Generated by scripts/generate-resource-guru-operation-registry.mjs.\n` +
  `// Source: ${docsUrl}.\n` +
  `// SHA-256: ${sourceHash}\n\n` +
  `export type ResourceGuruOperation = {\n  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n  path: string;\n  summary: string;\n  pathParameters: readonly string[];\n  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n};\n\n` +
  `export const RESOURCE_GURU_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n\n` +
  `export const RESOURCE_GURU_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly ResourceGuruOperation[];\n\n` +
  `export const RESOURCE_GURU_READ_OPERATION_IDS = RESOURCE_GURU_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
  `export const RESOURCE_GURU_MANAGE_OPERATION_IDS = RESOURCE_GURU_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n` +
  `export const RESOURCE_GURU_OPERATION_BY_ID = new Map<string, ResourceGuruOperation>(RESOURCE_GURU_OPERATIONS.map((operation) => [operation.id, operation]));\n`;
await writeFile(fileURLToPath(outputUrl), generated, "utf8");
console.log(
  JSON.stringify({
    sourceHash,
    operations: unique.length,
    reads,
    writes: unique.length - reads,
  }),
);
