import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const docsUrl = "https://timedoctor.redoc.ly/";
const htmlResponse = await fetch(docsUrl, { redirect: "error" });
if (!htmlResponse.ok)
  throw new Error(`${docsUrl} returned ${htmlResponse.status}`);
const html = await htmlResponse.text();
const statePath = html.match(/src="([^"]*redocly-state-[^"]+\.js)"/)?.[1];
if (!statePath)
  throw new Error("Time Doctor documentation state script was not found.");
const stateUrl = new URL(statePath, docsUrl).toString();
const stateResponse = await fetch(stateUrl, { redirect: "error" });
if (!stateResponse.ok)
  throw new Error(`${stateUrl} returned ${stateResponse.status}`);
const stateScript = await stateResponse.text();
const encodedState = stateScript.match(
  /^const __redoc_state = JSON\.parse\((.*)\);?\s*$/s,
)?.[1];
if (!encodedState)
  throw new Error("Time Doctor OpenAPI state could not be decoded.");
const state = JSON.parse(JSON.parse(encodedState));
const spec = state?.spec?.data;
if (spec?.openapi !== "3.0.2")
  throw new Error("Unexpected Time Doctor OpenAPI version.");

const sortDeep = (value) =>
  Array.isArray(value)
    ? value.map(sortDeep)
    : value && typeof value === "object"
      ? Object.fromEntries(
          Object.entries(value)
            .sort(([left], [right]) => left.localeCompare(right))
            .map(([key, item]) => [key, sortDeep(item)]),
        )
      : value;
const sourceSha256 = createHash("sha256")
  .update(JSON.stringify(sortDeep(spec)))
  .digest("hex");

// These are provider sign-in, registration, password, token, SSO, and callback
// surfaces. They are not workspace resources and must never become agent tools.
const excludedOperationIds = new Set([
  "login",
  "register",
  "registerSignup",
  "putProfile",
  "restorePassword",
  "authorization",
  "authorizationLogin",
  "logout",
  "logoutById",
  "login2faNew",
  "login2faActivate",
  "loginOauth2",
  "findMyCompany",
  "oneTimeLogin",
  "findMyCompanyCode",
  "checkSsoOtp",
  "ssoAuthorize",
  "getUsersTokens",
  "getFileSignedUrl",
  "getCalendarAuthUrl",
  "calendarPublicWebhookReceiver",
  "calendarHandleCallback",
  "refreshCalendarToken",
]);

const resolveRef = (value) => {
  if (!value?.$ref) return value;
  if (!value.$ref.startsWith("#/"))
    throw new Error(`External reference is not supported: ${value.$ref}`);
  return value.$ref
    .slice(2)
    .split("/")
    .reduce(
      (current, part) =>
        current?.[part.replaceAll("~1", "/").replaceAll("~0", "~")],
      spec,
    );
};

const methods = new Set(["get", "post", "put", "patch", "delete"]);
const operations = [];
for (const [path, pathItem] of Object.entries(spec.paths)) {
  for (const [rawMethod, rawOperation] of Object.entries(pathItem)) {
    const method = rawMethod.toLowerCase();
    if (
      !methods.has(method) ||
      excludedOperationIds.has(rawOperation.operationId)
    )
      continue;
    const parameters = [
      ...(pathItem.parameters ?? []),
      ...(rawOperation.parameters ?? []),
    ].map(resolveRef);
    const pathParameters = parameters
      .filter((parameter) => parameter.in === "path")
      .map((parameter) => parameter.name);
    const queryParameters = parameters
      .filter((parameter) => parameter.in === "query")
      .map((parameter) => parameter.name);
    operations.push({
      id: rawOperation.operationId,
      method: method.toUpperCase(),
      path,
      group: rawOperation.tags?.[0] ?? "Time Doctor",
      pathParameters: [...new Set(pathParameters)],
      queryParameters: [...new Set(queryParameters)],
      bodyAllowed: Boolean(rawOperation.requestBody),
    });
  }
}

const unique = [
  ...new Map(operations.map((operation) => [operation.id, operation])).values(),
].sort((left, right) => left.id.localeCompare(right.id));
const reads = unique.filter((operation) => operation.method === "GET").length;
const mutations = unique.length - reads;
if (unique.length !== 119 || reads !== 61 || mutations !== 58) {
  throw new Error(
    `Unexpected Time Doctor surface: ${unique.length}/${reads}/${mutations}`,
  );
}

const output = resolve(
  "backend/src/modules/marketplace/connectors/time-doctor/time-doctor-operation-registry.ts",
);
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/generate-time-doctor-operation-registry.mjs.\n` +
    `// Source: ${docsUrl}\n` +
    `// Canonical OpenAPI SHA-256: ${sourceSha256}\n\n` +
    `export type TimeDoctorOperation = {\n` +
    `  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n` +
    `  path: string;\n  group: string;\n  pathParameters: readonly string[];\n` +
    `  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n};\n\n` +
    `export const TIME_DOCTOR_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};\n\n` +
    `export const TIME_DOCTOR_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly TimeDoctorOperation[];\n\n` +
    `export const TIME_DOCTOR_OPERATION_BY_ID: ReadonlyMap<string, TimeDoctorOperation> = new Map(TIME_DOCTOR_OPERATIONS.map((operation) => [operation.id, operation]));\n` +
    `export const TIME_DOCTOR_READ_OPERATION_IDS = TIME_DOCTOR_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
    `export const TIME_DOCTOR_MANAGE_OPERATION_IDS = TIME_DOCTOR_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n`,
);
console.log(
  JSON.stringify(
    { output, sourceSha256, operations: unique.length, reads, mutations },
    null,
    2,
  ),
);
