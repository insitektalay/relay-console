#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const indexUrl = "https://developers.7shifts.com/llms.txt";
const outputUrl = new URL(
  "../backend/src/modules/marketplace/connectors/seven-shifts/seven-shifts-operation-registry.ts",
  import.meta.url,
);

async function fetchText(url) {
  const response = await fetch(url, {
    headers: { Accept: "text/markdown, text/plain" },
    redirect: "error",
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  return response.text();
}

const index = await fetchText(indexUrl);
const urls = [
  ...index.matchAll(
    /https:\/\/developers\.7shifts\.com\/reference\/[A-Za-z0-9_-]+\.md/g,
  ),
]
  .map((match) => match[0])
  .filter((url, index, all) => all.indexOf(url) === index);
const pages = [];
for (let offset = 0; offset < urls.length; offset += 8) {
  pages.push(
    ...(await Promise.all(
      urls
        .slice(offset, offset + 8)
        .map(async (url) => ({ url, text: await fetchText(url) })),
    )),
  );
}

const operations = [];
const hash = createHash("sha256").update(index);
for (const page of pages) {
  hash.update(page.url).update(page.text);
  const match = page.text.match(
    /# OpenAPI definition[\s\S]*?```json\s*([\s\S]*?)```/,
  );
  if (!match) continue;
  const document = JSON.parse(match[1]);
  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    for (const method of ["get", "post", "put", "patch", "delete"]) {
      const operation = pathItem[method];
      if (!operation?.operationId || operation["x-public-api"] !== true)
        continue;
      if (
        ["oauthToken", "partnerCompanyCreation"].includes(operation.operationId)
      )
        continue;
      const parameters = [
        ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
        ...(Array.isArray(operation.parameters) ? operation.parameters : []),
      ];
      operations.push({
        id: operation.operationId,
        method: method.toUpperCase(),
        path,
        summary:
          operation.summary || operation.description || operation.operationId,
        pathParameters: parameters
          .filter((parameter) => parameter.in === "path")
          .map((parameter) => parameter.name),
        queryParameters: parameters
          .filter((parameter) => parameter.in === "query")
          .map((parameter) => parameter.name),
        bodyAllowed: Boolean(operation.requestBody),
      });
    }
  }
}

const unique = [
  ...new Map(operations.map((operation) => [operation.id, operation])).values(),
].sort((left, right) => left.id.localeCompare(right.id));
const reads = unique.filter((operation) => operation.method === "GET").length;
if (unique.length !== 152 || reads !== 68 || unique.length - reads !== 84) {
  throw new Error(
    `Expected 152 7shifts operations (68 reads, 84 writes), received ${unique.length} (${reads} reads)`,
  );
}
const sourceHash = hash.digest("hex");
const generated =
  `// Generated by scripts/generate-seven-shifts-operation-registry.mjs.\n` +
  `// Source: ${indexUrl} and its official reference OpenAPI fragments.\n` +
  `// SHA-256: ${sourceHash}\n\n` +
  `export type SevenShiftsOperation = {\n  id: string;\n  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n  path: string;\n  summary: string;\n  pathParameters: readonly string[];\n  queryParameters: readonly string[];\n  bodyAllowed: boolean;\n};\n\n` +
  `export const SEVEN_SHIFTS_API_VERSION = "2026-06-01";\n` +
  `export const SEVEN_SHIFTS_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n\n` +
  `export const SEVEN_SHIFTS_OPERATIONS = ${JSON.stringify(unique, null, 2)} as const satisfies readonly SevenShiftsOperation[];\n\n` +
  `export const SEVEN_SHIFTS_READ_OPERATION_IDS = SEVEN_SHIFTS_OPERATIONS.filter((operation) => operation.method === "GET").map((operation) => operation.id);\n` +
  `export const SEVEN_SHIFTS_MANAGE_OPERATION_IDS = SEVEN_SHIFTS_OPERATIONS.filter((operation) => operation.method !== "GET").map((operation) => operation.id);\n` +
  `export const SEVEN_SHIFTS_OPERATION_BY_ID = new Map<string, SevenShiftsOperation>(SEVEN_SHIFTS_OPERATIONS.map((operation) => [operation.id, operation]));\n`;

await writeFile(fileURLToPath(outputUrl), generated, "utf8");
console.log(
  JSON.stringify({
    sourceHash,
    operations: unique.length,
    reads,
    writes: unique.length - reads,
  }),
);
